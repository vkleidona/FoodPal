package server;

import exceptions.ExistingFoodItemException;
import exceptions.MalformedRequestException;
import exceptions.ResourceNotFoundException;
import exceptions.ServerErrorException;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.ExceptionHandler;
import org.springframework.web.bind.annotation.RestControllerAdvice;

@RestControllerAdvice
public class GlobalExceptionHandler {

    /**
     * An Exception Handler for the custom ResourceNotFoundException class
     * @param e - the ResourceNotFoundException generated by the request
     * @return ResponseEntity <String> - returns a Not Found response with an explanation
     */
    @ExceptionHandler(ResourceNotFoundException.class)
    public ResponseEntity<String> handleNotFound(ResourceNotFoundException e) {
        return ResponseEntity.status(HttpStatus.NOT_FOUND).body(e.getMessage());
    }

    /**
     * An Exception Handler for the custom MalformedRequest class
     * @param e - the MalformedRequestException generated by the request
     * @return ResponseEntity <String> - returns a Malformed Request response with an explanation
     */
    @ExceptionHandler(MalformedRequestException.class)
    public ResponseEntity<String> handleMalformedRequest(MalformedRequestException e) {
        return ResponseEntity.status(HttpStatus.BAD_REQUEST).body(e.getMessage());
    }

    /**
     * An Exception Handler for the custom ServerErrorException class
     * @param e - the ServerErrorException generated by the request
     * @return ResponseEntity <String> - returns an InternalServerError response with an explanation
     */
    @ExceptionHandler(ServerErrorException.class)
    public ResponseEntity<String> handleServerError(ServerErrorException e) {
        return ResponseEntity.status(HttpStatus.INTERNAL_SERVER_ERROR).body(e.getMessage());
    }

    /**
     * An Exception Handler for the custom ServerErrorException class
     * @param e - the ServerErrorException generated by the request
     * @return ResponseEntity <String> - returns an InternalServerError response with an explanation
     */
    @ExceptionHandler(ExistingFoodItemException.class)
    public ResponseEntity<String> handleExistingItem(ServerErrorException e) {
        return ResponseEntity.status(HttpStatus.CONFLICT).body(e.getMessage());
    }
}

